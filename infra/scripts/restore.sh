#!/usr/bin/env sh
# `restore.bat|sh <файл>` — восстановление базы из бэкапа (SPEC.md 11.3).
#
# ⚠️ Это единственная деструктивная операция в проекте, направленная на живую базу.
# Отсюда весь порядок ниже:
#
# 1. Файл проверяется ДО того, как что-то трогается. Наполовину восстановленная база
#    хуже нетронутой: человек увидит журнал, в котором чего-то нет, и не поймёт чего.
# 2. Человеку показывается, что именно он теряет — счётчики текущей базы против
#    счётчиков внутри бэкапа, — и только потом спрашивается подтверждение.
# 3. Перед перезаписью снимается ещё один бэкап. Ошибиться файлом — самый вероятный
#    способ потерять данные этой командой, и он должен быть обратим.
# 4. Заливка идёт одной транзакцией с ON_ERROR_STOP: либо применилось всё, либо ничего.
set -eu

TD_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$TD_ROOT"
. "$TD_ROOT/infra/scripts/common.sh"

usage() {
  td_warn "Использование: $(td_script restore) <backups/td-….sql.gz> [--yes]"
  td_warn ""
  td_warn "  Заменяет содержимое базы данными из бэкапа."
  td_warn "  --yes — не спрашивать подтверждения (для неинтерактивного запуска)."
  td_warn ""
  td_warn "Доступные бэкапы:"
  available="$(ls -t "$TD_ROOT"/backups/td-*.sql.gz 2>/dev/null || true)"
  if [ -n "$available" ]; then
    printf '%s\n' "$available" | sed 's|^|      |' >&2
  else
    td_warn "      (в backups/ пусто — снимите копию: $(td_cmd backup))"
  fi
}

FILE=""
while [ $# -gt 0 ]; do
  case "$1" in
    --yes) TD_ASSUME_YES=1 ;;
    -h | --help)
      usage
      exit 0
      ;;
    -*)
      echo "restore: неизвестный аргумент '$1'" >&2
      usage
      exit 2
      ;;
    *)
      [ -z "$FILE" ] || {
        echo "restore: файл указывается один." >&2
        exit 2
      }
      FILE="$1"
      ;;
  esac
  shift
done

[ -n "$FILE" ] || {
  usage
  exit 2
}

# restore.bat backups\td-….sql.gz отдаёт путь с обратными слэшами, а в Git Bash разделитель
# только «/»: dirname такого пути вернёт «.», и файл начал бы искаться не там. Заменяем
# слэши лишь тогда, когда так файл находится: на macOS обратный слэш — легальный символ
# имени, и глобальная замена ломала бы правильный путь.
if [ ! -e "$FILE" ]; then
  ALT="$(printf '%s' "$FILE" | tr '\\' '/')"
  [ ! -e "$ALT" ] || FILE="$ALT"
fi

[ -f "$FILE" ] || td_die "Файл не найден: $FILE"
FILE="$(cd "$(dirname "$FILE")" && pwd)/$(basename "$FILE")"

td_require_installation
# До заливки, а не после: restore кончается вызовом start.sh, а тот из непригодного пути
# откажется работать (X-54). Довод тот же, что в update.sh, только сильнее — здесь между
# «начали» и «отказ» лежит перезаписанная база.
td_require_ascii_path
td_require_env
td_require_docker

## ----------------------------------------------------------------------------
## Проверка файла — до того, как тронута база
## ----------------------------------------------------------------------------

REPORT="$(mktemp "${TMPDIR:-/tmp}/td-restore.XXXXXX")"
trap 'rm -f "$REPORT"' EXIT INT TERM

td_say "Проверяю $FILE…"
td_verify_dump "$FILE" "$REPORT"
grep -q '^CREATED ' "$REPORT" ||
  td_die "В $FILE нет ни одной таблицы. Это не дамп базы TradeDesk."

# Наличия CREATE TABLE мало: дамп чужой базы проходит его так же, как наш, а заливка
# добавила бы чужие таблицы в базу журнала. Спрашиваем про таблицы, которые есть
# в TradeDesk с первой миграции.
NOT_OURS="$(td_dump_looks_like_tradedesk "$REPORT")"
[ -z "$NOT_OURS" ] ||
  td_die "В $FILE нет таблиц TradeDesk:$NOT_OURS

Похоже, это дамп другой базы. Восстановление отменено: его заливка добавила бы
чужие таблицы в базу журнала, а вернуть их обратно было бы нечем."

td_ensure_postgres

## ----------------------------------------------------------------------------
## Что именно перезаписываем
## ----------------------------------------------------------------------------

NOW="$(mktemp "${TMPDIR:-/tmp}/td-counts.XXXXXX")"
trap 'rm -f "$REPORT" "$NOW"' EXIT INT TERM
td_table_counts >"$NOW"

td_say ""
td_say "==============================================================="
td_say " ЧТО БУДЕТ ПЕРЕЗАПИСАНО"
td_say "==============================================================="
td_say ""
td_say "  База      $TD_PG_DB (том td_pgdata, контейнер postgres)"
td_say "  Из файла  $FILE"
td_say "  Размер    $(td_human_size "$FILE")"
td_say "  Дата      $(date -r "$FILE" '+%Y-%m-%d %H:%M:%S' 2>/dev/null ||
  stat -c '%y' "$FILE" 2>/dev/null || echo '?')"
td_say ""
td_say "    Таблица             сейчас в базе   станет из бэкапа"
td_restore_preview "$NOW" "$REPORT"
td_say ""
td_say "  «←» — строк станет меньше, чем сейчас. Разница будет потеряна."

ABSENT="$(td_dump_absent_tables "$NOW" "$REPORT" | tr '\n' ' ')"
if [ -n "$ABSENT" ]; then
  td_say ""
  td_say "  «останется как есть» — этих таблиц в бэкапе нет вовсе:"
  td_say "      $ABSENT"
  td_say "  Дамп сносит только то, что в нём есть, поэтому их строки уцелеют и лягут"
  td_say "  ПОВЕРХ восстановленных данных. Так выглядит бэкап более старой схемы:"
  td_say "  журнал вернётся из файла, а таблицы, появившиеся позже, останутся от"
  td_say "  сегодняшней базы. Смесь двух состояний — проверьте, что вы этого хотите."
fi

## ----------------------------------------------------------------------------
## Ключ, которым зашифрованы пароли счетов в этом бэкапе (ADR-0003, ADR-0005)
## ----------------------------------------------------------------------------

# Проверяемо, а не «имейте в виду»: key_version лежит рядом с каждым блобом внутри самого
# дампа. Отказом это не делается — журнал и рефлексии восстановятся в любом случае, а
# нечитаемыми останутся только сохранённые пароли счетов, которых после ADR-0006 не
# требует уже ничто. Но узнать человек должен ДО подтверждения.
KEYS_IN_DUMP="$(td_dump_key_versions "$FILE" | tr '\n' ' ')"
td_say ""

# Отпечаток считает контейнер api: на несобранном образе это займёт минуты, и молчать
# в этом месте нельзя — человек решит, что скрипт завис перед самым важным вопросом.
[ -z "$KEYS_IN_DUMP" ] || td_say "Сверяю MASTER_KEY с ключом из бэкапа…"

if [ -z "$KEYS_IN_DUMP" ]; then
  td_say "  MASTER_KEY: в бэкапе нет ни одного счёта с паролем — сверять нечего."
elif ! FP="$(td_key_fingerprints)"; then
  td_say "  MASTER_KEY: ⚠️  отпечаток текущего ключа посчитать не удалось (см. выше)."
  td_say "              Совпадает ли он с ключом этого бэкапа — неизвестно. Если .env"
  td_say "              с тех пор менялся, пароли счетов не расшифруются."
else
  FP_CUR="$(printf '%s\n' "$FP" | awk '$1 == "cur" { print $2 }' | tr -d '\r')"
  FP_PREV="$(printf '%s\n' "$FP" | awk '$1 == "prev" { print $2 }' | tr -d '\r')"
  # shellcheck disable=SC2086
  VERDICT="$(td_key_verdict "$FP_CUR" "$FP_PREV" $KEYS_IN_DUMP)"
  UNKNOWN_KEYS="$(printf '%s' "$VERDICT" | cut -f2)"
  case "$(printf '%s' "$VERDICT" | cut -f1)" in
    current)
      td_say "  MASTER_KEY: совпал — пароли счетов из бэкапа расшифруются."
      ;;
    previous)
      td_say "  MASTER_KEY: пароли в бэкапе на ПРЕДЫДУЩЕМ ключе (MASTER_KEY_PREVIOUS)."
      td_say "              Расшифруются, но ротацию после восстановления надо допрогнать."
      ;;
    *)
      td_say "  MASTER_KEY: ⚠️  НЕ ТОТ. Пароли счетов в этом бэкапе зашифрованы ключом,"
      td_say "              которого нет в вашем .env (отпечатки в бэкапе: $UNKNOWN_KEYS)."
      td_say "              На работу это не влияет: журнал, сделки и рефлексии вернутся"
      td_say "              целиком, а синхронизации пароль счёта не нужен — в MetaTrader 5"
      td_say "              вы входите сами. Нечитаемыми останутся сами эти пароли, и"
      td_say "              восстановление не чинит этого: ключ лежит в .env, а не в базе."
      ;;
  esac
fi
td_say ""

td_confirm "restore" "Продолжить? Текущее содержимое базы будет заменено."

## ----------------------------------------------------------------------------
## Страховка: бэкап того, что сейчас
## ----------------------------------------------------------------------------

# Ошибиться файлом — самый вероятный способ потерять данные этой командой. Свежий дамп
# перед перезаписью делает ошибку обратимой; без него «восстановил не то» необратимо.
td_say ""
td_say "Сначала — бэкап текущего состояния, на случай если файл выбран не тот."
SAFETY_OUT="$(mktemp "${TMPDIR:-/tmp}/td-safety.XXXXXX")"
TD_BACKUP_PATH_OUT="$SAFETY_OUT" "$TD_ROOT/infra/scripts/backup.sh" ||
  td_die "Страховочный бэкап не снялся — восстановление отменено, база не тронута."
SAFETY="$(cat "$SAFETY_OUT")"
rm -f "$SAFETY_OUT"

## ----------------------------------------------------------------------------
## Заливка
## ----------------------------------------------------------------------------

# api и worker держат соединения и получили бы DROP TABLE под собой. Гасим их, но не
# postgres: заливать некуда, если погасить и его.
td_say ""
td_say "Останавливаю api и worker на время заливки…"
td_compose stop api worker >/dev/null 2>&1 || true

# --single-transaction + ON_ERROR_STOP: либо применилось всё, либо база осталась прежней.
# Без этого битый дамп оставил бы половину таблиц восстановленными, а половину — нет,
# и разницу никто бы не заметил до первого открытого экрана.
td_say "Заливаю дамп одной транзакцией…"
set +e
gzip -dc "$FILE" | td_compose exec -T postgres \
  psql -X -q -v ON_ERROR_STOP=1 --single-transaction \
  -U "$TD_PG_USER" -d "$TD_PG_DB" >/dev/null
PSQL_STATUS=$?
set -e

if [ "$PSQL_STATUS" != "0" ]; then
  td_say ""
  td_say "Поднимаю api и worker обратно…"
  td_compose up -d >/dev/null 2>&1 || true
  td_die "psql завершился с кодом $PSQL_STATUS — транзакция откачена, база НЕ изменена.
Страховочный бэкап на месте: $SAFETY"
fi

td_say ""
td_say "Поднимаю приложение…"
"$TD_ROOT/infra/scripts/start.sh" || td_die "Данные восстановлены, но приложение не поднялось.
Смотрите: docker compose logs api"

td_ensure_postgres
td_say ""
td_say "Восстановлено. Сейчас в базе:"
td_table_counts | td_print_counts
td_say ""
td_say "Состояние до восстановления сохранено здесь: $SAFETY"
