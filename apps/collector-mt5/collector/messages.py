def describe_mt5_failure(code: int, description: str, *, stage: Stage) -> str:
    """Код и текст терминала → фраза, по которой человек поймёт, что чинить.

    Чистая функция: ни терминала, ни сети. Отсюда и берётся `message` heartbeat'а. Ни
    номера счёта, ни имени сервера здесь не подставляется: коллектор больше не входит в
    терминал параметрами, и на шаге подключения он ещё не знает, чей счёт там открыт.
    """
    text = _by_code(code, stage=stage)
    if text is None:
        text = UNKNOWN_MT5_ERROR
    return fit(text.format(code=code, description=description or "пусто"))


def _by_code(code: int, *, stage: Stage) -> str | None:
    if code in LINK_FAILURES:
        # Единственная развилка, которая у семейства есть: на подключении человеку надо
        # открыть терминал, а посреди работы — ничего, коллектор переподключится сам.
        return TERMINAL_NOT_OPEN if stage == "connect" else TERMINAL_LOST
    if code == RES_E_AUTH_FAILED:
        return NOT_AUTHORIZED
    if code == RES_E_INVALID_PARAMS:
        return INVALID_PARAMS
    if code == RES_E_NO_MEMORY:
        return NO_MEMORY
    if code == RES_E_NOT_FOUND:
        return NO_HISTORY if stage == "history" else NOTHING_FOUND
    if code == RES_E_INVALID_VERSION:
        return INVALID_VERSION
    if code == RES_E_UNSUPPORTED:
        return UNSUPPORTED
    if code == RES_E_AUTO_TRADING_DISABLED:
        return AUTO_TRADING_DISABLED
    return None
