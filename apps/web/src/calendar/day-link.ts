/**
 * Ссылка из календаря в журнал за один торговый день.
 *
 * ⚠️ Границы приходят из ответа календаря и подставляются **как есть**: правило торгового
 * дня живёт одним выражением на сервере (SPEC.md 5.4, `docs/metrics.md` §2.2), и второй
 * его реализации на клиенте нет. Разойдясь, календарь показал бы сделку в понедельник, а
 * журнал за понедельник её не нашёл бы.
 *
 * `status=closed` обязателен и не является украшением: без него в список приедут ещё и
 * позиции, открытые внутри этого окна, — у них своего дня нет, в календаре их нет вовсе
 * (`docs/metrics.md` §5), и сумма колонки журнала разошлась бы с числом в ячейке. Ровно
 * это расхождение DoD `S2-09` и запрещает.
 */
import { PARAM } from '@/journal/filters';

export function journalDayLink(startsAt: string, endsAt: string): string {
  const params = new URLSearchParams({
    [PARAM.from]: startsAt,
    [PARAM.to]: endsAt,
    [PARAM.status]: 'closed',
  });
  return `/journal?${params.toString()}`;
}
