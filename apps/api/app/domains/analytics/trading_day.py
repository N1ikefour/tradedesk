"""Торговый день пользователя в SQL — единственное место, где живёт это правило.

Правило целиком — `docs/metrics.md` §2:

> торговый день `D` — полуинтервал `[начало(D), начало(D+1))`, где `начало(D)` — первый
> момент, в который стенные часы пользователя показывают `day_boundary_hour` даты `D`.

День задан **интервалом**, а не формулой «дата минус час», и отсюда растёт вся конструкция
ниже: дни строятся один раз списком с границами, а позиции присоединяются к ним сравнением
`close_time` с этими же границами. Поэтому «в каком дне позиция» и «какие границы у дня»
не могут разойтись — это одно и то же выражение, а не два. Разойдясь, они дали бы ровно тот
дефект, ради которого правило вообще вынесено сюда: календарь показывает сделку в
понедельник, а журнал за понедельник её не находит.

**Поправка на час.** `timezone(tz, D + h часов)` — это «момент, когда стенные часы
показали `h`», но осенью такой час случается дважды, и Postgres возвращает **второе**
вхождение. Первое тогда попадёт в предыдущий день, хотя стенные часы уже показывают новый:
сутки пересекутся. Поэтому кандидат сдвигается на час назад, если и он попадает в тот же
торговый день. На весеннем переходе, где стенного времени `h` не существует вовсе,
Postgres сам отдаёт первый существующий момент после пропуска, и поправка не срабатывает.

Проверено перебором: 9 зон (включая `Pacific/Chatham` со сдвигом +12:45 и
`Australia/Lord_Howe` с получасовым переводом) × 24 значения границы × 5 лет — начала дней
строго возрастают, длина суток всегда между 22 и 26 часами, и каждый момент попадает ровно
в один день. Тест — `tests/integration/test_analytics.py`.

Приведение параметров написано через `cast(:name as ...)`, а не `:name::type`: разбор
`text()` в SQLAlchemy не считает параметром имя, за которым сразу идёт двоеточие, и такой
запрос молча уезжает в базу с нераскрытым `:first_day`.

Почему сырой SQL, а не выражения SQLAlchemy Core: `generate_series` с оконной функцией и
боковым соединением на Core читается вдвое длиннее и вдвое хуже. Значения приходят
**только** через bind-параметры (`:timezone`, `:day_boundary_hour`, `:first_day`,
`:last_day`), поэтому в текст запроса ничего пользовательского не подставляется — в лог
такой запрос уезжает с плейсхолдерами (`core/db.py::describe_database_error`).
"""

from __future__ import annotations

# Отдельный день с его границами. `lead` даёт конец дня из начала следующего — так конец
# одного дня и начало другого это буквально одно значение, без второго вычисления.
# Ряд генерируется на день дальше запрошенного и лишняя строка отбрасывается: последнему
# дню тоже нужен сосед справа.
DAYS_CTE = """
days as (
    select day, starts_at, ends_at
    from (
        select
            bounds.day,
            bounds.starts_at,
            lead(bounds.starts_at) over (order by bounds.day) as ends_at
        from (
            select
                dates.day,
                case
                    when (
                        timezone(:timezone, candidate.moment - interval '1 hour')
                        - make_interval(hours => :day_boundary_hour)
                    )::date = dates.day
                    then candidate.moment - interval '1 hour'
                    else candidate.moment
                end as starts_at
            from (
                select moment::date as day
                from generate_series(
                    cast(:first_day as timestamp),
                    cast(:last_day as timestamp) + interval '1 day',
                    interval '1 day'
                ) as moment
            ) as dates
            cross join lateral (
                select timezone(
                    :timezone,
                    dates.day::timestamp + make_interval(hours => :day_boundary_hour)
                ) as moment
            ) as candidate
        ) as bounds
    ) as windows
    where ends_at is not null
)
"""

