@dataclass(frozen=True, slots=True)
class ResolvedSymbol:
    """Сырой символ и то, что о нём удалось понять. Строка `symbols` без её id и источника."""

    raw: str
    norm: str
    asset_class: AssetClass


def clean_symbol(raw: str) -> str:
    """Верхний регистр и суффиксы брокера, срезанные итеративно (SPEC.md 6.4).

    Итеративно — чтобы `EURUSD.m.raw` схлопнулся до `EURUSD`, а не до `EURUSD.M`: суффиксы
    у брокеров сочетаются, и одного прохода хватает не всегда.

    Пустой результат не возвращается никогда. Символ, состоящий из одного суффикса (`.m`,
    `_1`), очистился бы в пустую строку, и инструмент потерял бы имя совсем — а `norm`
    в `symbols` NOT NULL, и по нему же фильтрует журнал. Такой шаг откатывается: остаётся
    последнее непустое значение. Молча испортить имя хуже, чем не узнать его.
    """
    cleaned = raw.upper()
    while True:
        stripped = _SUFFIX_RE.sub("", cleaned)
        # Каждый шаг строго укорачивает строку, поэтому цикл конечен: первое же совпадение,
        # которое ничего не срезало или срезало всё, его и заканчивает.
        if stripped == cleaned or not stripped:
            return cleaned
        cleaned = stripped


def resolve_symbol(raw: str) -> ResolvedSymbol:
    """Символ брокера → имя инструмента и класс актива (SPEC.md 6.4).

    Провал сверки со словарём — не ошибка: инструмент остаётся в журнале под очищенным
    именем и классом `other`. Терять сделку из-за незнакомого тикера нельзя, а угадывать
    класс по форме имени (шесть букв — значит fx) — это уже додумывать за брокера.
    """
    norm = clean_symbol(raw)
    return ResolvedSymbol(
        raw=raw, norm=norm, asset_class=KNOWN_SYMBOLS.get(norm, UNKNOWN_ASSET_CLASS)
    )
